-- Before:
--   Q: 「日本語を話すことができます。」の意味は？
--   [*] "日本語を話すことができます"  ← 원문 그대로 (A2 누설)
--   "日本語を話したいです" / "日本語を話さなければなりません" / "日本語を話しています"
--
-- After:
--   Q: 「日本語を話すことができます。」と同じ意味の文はどれですか？
--   [*] "日本語が話せます"  ← 可能形으로 환언
--   (나머지 3개 오답 유지: 希望/義務/進行 문법 테스트)

UPDATE quiz_questions
SET question_text = '「日本語を話すことができます。」と同じ意味の文はどれですか？',
    explanation = '「〜ことができる」は能力や可能性を表す文型で「~할 수 있다」という意味です。動詞の可能形「話せる」と同じ意味を持ちます。他の選択肢は「〜たい」(希望)、「〜なければならない」(義務)、「〜ている」(進行) でそれぞれ違う文型です。'
WHERE id = '647ab6eb-fabe-46d5-85dc-ede28319d6be';

UPDATE quiz_question_options
SET option_text = '日本語が話せます'
WHERE id = '84853465-1fba-43fd-99d9-ac4e07b0eba0';

