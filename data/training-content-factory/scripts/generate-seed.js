/**
 * generate-seed.js
 *
 * 콘텐츠 팩토리 출력물(MDX/quiz.json/lab.md)을 Supabase DB 시드 SQL로 변환한다.
 *
 * 사용법:  node data/training-content-factory/scripts/generate-seed.js
 * 출력:    supabase/seed_java_content.sql
 */

const fs = require('fs');
const path = require('path');
const crypto = require('crypto');

// ─── Paths ──────────────────────────────────────────────
const ROOT = path.resolve(__dirname, '..', '..', '..');
const CONTENT_DIR = path.join(ROOT, 'data', 'training-content-factory', 'content', 'java');
const OUTPUT_FILE = path.join(ROOT, 'supabase', 'seed_java_content.sql');

// ─── Deterministic UUID ─────────────────────────────────
const NAMESPACE = 'jbridge-content-factory';

function makeUUID(name) {
  const hash = crypto.createHash('md5')
    .update(NAMESPACE + ':' + name)
    .digest('hex');
  return [
    hash.slice(0, 8),
    hash.slice(8, 12),
    '4' + hash.slice(13, 16),
    'a' + hash.slice(17, 20),
    hash.slice(20, 32),
  ].join('-');
}

// ─── Lightweight YAML parser ────────────────────────────
// track.yaml / module.yaml are simple enough for regex-based parsing.

function parseTrackYaml(text) {
  const modules = [];
  // Match each module entry block
  const moduleBlocks = text.split(/\n\s+-\s+id:\s+/).slice(1);
  for (const block of moduleBlocks) {
    const lines = ('id: ' + block).split('\n');
    const entry = {};
    for (const line of lines) {
      const m = line.match(/^\s*(id|title|level|order):\s+(.+)/);
      if (m) {
        const key = m[1];
        let val = m[2].trim();
        // strip quotes
        val = val.replace(/^["']|["']$/g, '');
        entry[key] = key === 'order' ? parseInt(val, 10) : val;
      }
    }
    if (entry.id) modules.push(entry);
  }
  return modules;
}

function parseModuleYaml(text) {
  const result = { id: '', title: '', level: '', description: '', lessons: [] };

  // Top-level fields
  const idMatch = text.match(/^\s+id:\s+(.+)/m);
  if (idMatch) result.id = idMatch[1].trim();

  const titleMatch = text.match(/^\s+title:\s+(.+)/m);
  if (titleMatch) result.title = titleMatch[1].trim().replace(/^["']|["']$/g, '');

  const levelMatch = text.match(/^\s+level:\s+(.+)/m);
  if (levelMatch) result.level = levelMatch[1].trim();

  const descMatch = text.match(/^\s+description:\s+(.+)/m);
  if (descMatch) result.description = descMatch[1].trim().replace(/^["']|["']$/g, '');

  // Lessons
  const lessonBlocks = text.split(/\n\s+-\s+id:\s+/).slice(1);
  for (const block of lessonBlocks) {
    const lines = ('id: ' + block).split('\n');
    const lesson = {};
    for (const line of lines) {
      const m = line.match(/^\s*(id|title|est_minutes):\s+(.+)/);
      if (m) {
        const key = m[1];
        let val = m[2].trim().replace(/^["']|["']$/g, '');
        lesson[key] = key === 'est_minutes' ? parseInt(val, 10) : val;
      }
    }
    if (lesson.id) result.lessons.push(lesson);
  }

  return result;
}

// ─── MDX frontmatter parser ─────────────────────────────

function parseMdxFrontmatter(text) {
  const m = text.match(/^---\n([\s\S]*?)\n---/);
  if (!m) return {};
  const fm = {};
  for (const line of m[1].split('\n')) {
    const kv = line.match(/^(\w+):\s+(.+)/);
    if (kv) {
      let val = kv[2].trim().replace(/^["']|["']$/g, '');
      fm[kv[1]] = val;
    }
  }
  return fm;
}

// ─── Level → difficulty mapping ─────────────────────────

function levelToDifficulty(level) {
  const map = { bronze: 'beginner', silver: 'intermediate', gold: 'advanced' };
  return map[level] || 'beginner';
}

// coding_problems.difficulty CHECK (IN ('easy','medium','hard'))
function levelToCodingDifficulty(level) {
  const map = { bronze: 'easy', silver: 'medium', gold: 'hard' };
  return map[level] || 'easy';
}

// ─── Quiz difficulty → question difficulty ──────────────

function quizDifficultyToEnum(d) {
  if (d <= 2) return 'easy';
  if (d === 3) return 'medium';
  return 'hard';
}

// ─── SQL string escape ──────────────────────────────────

function esc(str) {
  if (str == null) return '';
  return str
    .replace(/\\/g, '\\\\')
    .replace(/'/g, "''")
    .replace(/\n/g, '\\n')
    .replace(/\r/g, '')
    .replace(/\t/g, '\\t');
}

// ─── Main ───────────────────────────────────────────────

function main() {
  const trackYaml = fs.readFileSync(path.join(CONTENT_DIR, 'track.yaml'), 'utf8');
  const trackModules = parseTrackYaml(trackYaml);

  const lines = [];

  lines.push('-- ============================================');
  lines.push('-- J-Bridge Seed Data: Java 開発実務能力コンテンツ');
  lines.push('-- Generated by: generate-seed.js');
  lines.push(`-- Generated at: ${new Date().toISOString()}`);
  lines.push('-- ============================================');
  lines.push('');

  let stats = { courses: 0, lessons: 0, quizzes: 0, questions: 0, options: 0, codingProblems: 0 };

  for (const trackMod of trackModules) {
    const moduleDir = path.join(CONTENT_DIR, 'modules', trackMod.id);
    const moduleYamlPath = path.join(moduleDir, 'module.yaml');

    if (!fs.existsSync(moduleYamlPath)) {
      console.log(`⚠️  ${trackMod.id}/module.yaml not found, skipping.`);
      continue;
    }

    const moduleYaml = fs.readFileSync(moduleYamlPath, 'utf8');
    const mod = parseModuleYaml(moduleYaml);

    const courseUUID = makeUUID('course:' + mod.id);
    const difficulty = levelToDifficulty(mod.level);

    lines.push('-- ============================================');
    lines.push(`-- Course: ${mod.id} (${mod.title})`);
    lines.push('-- ============================================');
    lines.push('');
    lines.push(`INSERT INTO courses (id, title, description, category, subcategory, difficulty, is_published, sort_order)`);
    lines.push(`VALUES ('${courseUUID}', E'${esc(mod.title)}', E'${esc(mod.description)}', 'core_programming', 'java', '${difficulty}', TRUE, ${trackMod.order})`);
    lines.push(`ON CONFLICT (id) DO UPDATE SET title=EXCLUDED.title, description=EXCLUDED.description, subcategory=EXCLUDED.subcategory, difficulty=EXCLUDED.difficulty, sort_order=EXCLUDED.sort_order;`);
    lines.push('');
    stats.courses++;

    // Process lessons
    let lessonOrder = 0;
    for (const lessonMeta of mod.lessons) {
      const lessonsDir = path.join(moduleDir, 'lessons');
      const mdxPath = path.join(lessonsDir, lessonMeta.id + '.mdx');

      // Only process lessons that have actual content files
      if (!fs.existsSync(mdxPath)) {
        continue;
      }

      lessonOrder++;
      const lessonUUID = makeUUID('lesson:' + lessonMeta.id);
      const mdxContent = fs.readFileSync(mdxPath, 'utf8');
      const fm = parseMdxFrontmatter(mdxContent);
      const lessonTitle = fm.title || lessonMeta.title;
      const estMinutes = parseInt(fm.est_minutes || lessonMeta.est_minutes, 10) || 30;

      // Check for Korean translation
      const koMdxPath = path.join(lessonsDir, lessonMeta.id + '.ko.mdx');
      const hasKo = fs.existsSync(koMdxPath);
      const koContent = hasKo ? fs.readFileSync(koMdxPath, 'utf8') : null;

      lines.push(`-- Lesson: ${lessonMeta.id} (${lessonTitle})`);
      if (koContent) {
        lines.push(`INSERT INTO lessons (id, course_id, title, content_type, content_body, content_body_ko, duration_minutes, sort_order)`);
        lines.push(`VALUES ('${lessonUUID}', '${courseUUID}', E'${esc(lessonTitle)}', 'text', E'${esc(mdxContent)}', E'${esc(koContent)}', ${estMinutes}, ${lessonOrder})`);
      } else {
        lines.push(`INSERT INTO lessons (id, course_id, title, content_type, content_body, duration_minutes, sort_order)`);
        lines.push(`VALUES ('${lessonUUID}', '${courseUUID}', E'${esc(lessonTitle)}', 'text', E'${esc(mdxContent)}', ${estMinutes}, ${lessonOrder})`);
      }
      lines.push(`ON CONFLICT (id) DO NOTHING;`);
      lines.push('');
      stats.lessons++;

      // ── Quiz ────────────────────────────────────
      const quizPath = path.join(lessonsDir, lessonMeta.id + '.quiz.json');
      if (fs.existsSync(quizPath)) {
        const quizData = JSON.parse(fs.readFileSync(quizPath, 'utf8'));
        const quizUUID = makeUUID('quiz:' + lessonMeta.id);

        lines.push(`-- Quiz: ${lessonMeta.id}`);
        lines.push(`INSERT INTO quizzes (id, lesson_id, title, quiz_type, passing_score, time_limit_minutes)`);
        lines.push(`VALUES ('${quizUUID}', '${lessonUUID}', E'${esc(lessonTitle + ' 理解度テスト')}', 'core_programming', 70, 15)`);
        lines.push(`ON CONFLICT (id) DO NOTHING;`);
        lines.push('');
        stats.quizzes++;

        let qOrder = 0;
        for (const q of quizData.questions) {
          qOrder++;
          const qUUID = makeUUID('question:' + q.id);
          const diffEnum = quizDifficultyToEnum(q.difficulty);

          // Build question_text and options based on type
          let questionText = '';
          let options = []; // { text, is_correct }
          let todoComment = '';

          if (q.type === 'single_choice') {
            questionText = q.prompt;
            options = q.choices.map((c, i) => ({
              text: c,
              is_correct: i === q.answer,
            }));
          } else if (q.type === 'code_output') {
            questionText = q.prompt + '\n\n```java\n' + q.code + '\n```';
            todoComment = '-- TODO: code_output の選択肢を確認';
            options = [
              { text: q.answer, is_correct: true },
              { text: '（ダミー選択肢A）', is_correct: false },
              { text: '（ダミー選択肢B）', is_correct: false },
              { text: '（ダミー選択肢C）', is_correct: false },
            ];
          } else if (q.type === 'short_answer') {
            questionText = q.prompt;
            todoComment = '-- TODO: short_answer の選択肢を確認';
            options = [
              { text: q.answer, is_correct: true },
              { text: '（ダミー選択肢A）', is_correct: false },
              { text: '（ダミー選択肢B）', is_correct: false },
              { text: '（ダミー選択肢C）', is_correct: false },
            ];
          } else if (q.type === 'multi_choice') {
            // Treat as multiple_choice; mark first correct answer
            questionText = q.prompt;
            const correctSet = new Set(Array.isArray(q.answer) ? q.answer : [q.answer]);
            options = q.choices.map((c, i) => ({
              text: c,
              is_correct: correctSet.has(i),
            }));
          } else if (q.type === 'true_false') {
            questionText = q.prompt;
            todoComment = '-- TODO: true_false の選択肢を確認';
            options = [
              { text: 'TRUE', is_correct: q.answer === true },
              { text: 'FALSE', is_correct: q.answer === false },
              { text: '（ダミー選択肢A）', is_correct: false },
              { text: '（ダミー選択肢B）', is_correct: false },
            ];
          }

          if (todoComment) lines.push(todoComment);

          lines.push(`INSERT INTO quiz_questions (id, quiz_id, question_type, question_text, explanation, points, sort_order, difficulty)`);
          lines.push(`VALUES ('${qUUID}', '${quizUUID}', 'multiple_choice', E'${esc(questionText)}', E'${esc(q.explanation)}', 10, ${qOrder}, '${diffEnum}')`);
          lines.push(`ON CONFLICT (id) DO NOTHING;`);
          lines.push('');
          stats.questions++;

          // Options
          const optionValues = options.map((opt, i) => {
            const optUUID = makeUUID('option:' + q.id + '-' + (i + 1));
            stats.options++;
            return `('${optUUID}', '${qUUID}', E'${esc(opt.text)}', ${opt.is_correct ? 'TRUE' : 'FALSE'}, ${i + 1})`;
          });

          lines.push(`INSERT INTO quiz_question_options (id, question_id, option_text, is_correct, sort_order) VALUES`);
          lines.push(optionValues.join(',\n'));
          lines.push(`ON CONFLICT (id) DO NOTHING;`);
          lines.push('');
        }
      }

      // ── Coding Problem (lab) ────────────────────
      const labPath = path.join(lessonsDir, lessonMeta.id + '.lab.md');
      if (fs.existsSync(labPath)) {
        const labContent = fs.readFileSync(labPath, 'utf8');
        const codingUUID = makeUUID('coding:' + lessonMeta.id);
        const labTitle = lessonTitle + ' 実践ラボ';

        lines.push(`-- Coding Problem: ${lessonMeta.id}`);
        lines.push(`INSERT INTO coding_problems (id, lesson_id, title, description, difficulty, language)`);
        lines.push(`VALUES ('${codingUUID}', '${lessonUUID}', E'${esc(labTitle)}', E'${esc(labContent)}', '${levelToCodingDifficulty(mod.level)}', 'java')`);
        lines.push(`ON CONFLICT (id) DO NOTHING;`);
        lines.push('');
        stats.codingProblems++;
      }
    }
  }

  // Write output
  const sql = lines.join('\n') + '\n';
  fs.writeFileSync(OUTPUT_FILE, sql, 'utf8');

  console.log(`✅ Generated: ${OUTPUT_FILE}`);
  console.log('');
  console.log('📊 Stats:');
  console.log(`   Courses:         ${stats.courses}`);
  console.log(`   Lessons:         ${stats.lessons}`);
  console.log(`   Quizzes:         ${stats.quizzes}`);
  console.log(`   Quiz Questions:  ${stats.questions}`);
  console.log(`   Quiz Options:    ${stats.options}`);
  console.log(`   Coding Problems: ${stats.codingProblems}`);
}

main();
